use crate::domain::{Ear, FREQUENCIES_HZ, TestSession, ThresholdOutcome, compare_sessions};
use printpdf::{
    BuiltinFont, Color, Line, LineDashPattern, LinePoint, Mm, Op, PaintMode, PdfDocument,
    PdfFontHandle, PdfPage, PdfSaveOptions, Point, Polygon, PolygonRing, Pt, Rgb, TextItem,
    WindingOrder,
};
use std::fs;
use std::path::Path;
use thiserror::Error;

const PAGE_WIDTH_MM: f32 = 297.0;
const PAGE_HEIGHT_MM: f32 = 210.0;
const PLOT_LEFT: f32 = 56.0;
const PLOT_RIGHT: f32 = 545.0;
const PLOT_TOP: f32 = 430.0;
const PLOT_BOTTOM: f32 = 205.0;

#[derive(Debug, Error)]
pub enum ReportError {
    #[error("could not write the report: {0}")]
    Io(#[from] std::io::Error),
}

pub fn save_pdf(
    path: &Path,
    session: &TestSession,
    baseline: Option<&TestSession>,
    display_name: Option<&str>,
) -> Result<(), ReportError> {
    fs::write(path, generate_pdf(session, baseline, display_name))?;
    Ok(())
}

pub fn generate_pdf(
    session: &TestSession,
    baseline: Option<&TestSession>,
    display_name: Option<&str>,
) -> Vec<u8> {
    let baseline = baseline.filter(|candidate| session.is_comparable_with(candidate));
    let mut ops = Vec::new();
    text(&mut ops, 42.0, 555.0, 19.0, "Personal Hearing Trend Report");
    text(
        &mut ops,
        42.0,
        535.0,
        10.0,
        "UNCALIBRATED - personal monitoring only; not a clinical audiogram",
    );
    let date = session.completed_at.unwrap_or(session.started_at).date();
    text(
        &mut ops,
        42.0,
        514.0,
        9.0,
        &format!(
            "Name: {}    Test date: {:04}-{:02}-{:02}    Session: {}",
            display_name
                .filter(|name| !name.trim().is_empty())
                .unwrap_or("Not provided"),
            date.year(),
            u8::from(date.month()),
            date.day(),
            session.id
        ),
    );
    text(
        &mut ops,
        42.0,
        500.0,
        8.0,
        &format!(
            "Output: {} | {} Hz | volume {} | {}",
            session.setup.device_name,
            session.setup.sample_rate,
            session
                .setup
                .sink_volume_percent
                .map(|value| format!("{value:.0}%"))
                .unwrap_or_else(|| "unavailable".to_owned()),
            session.setup.listening_mode
        ),
    );
    text(
        &mut ops,
        42.0,
        486.0,
        8.0,
        &format!(
            "Quality: {}{}",
            session
                .quality
                .as_ref()
                .map(|quality| quality.label())
                .unwrap_or("Not assessed"),
            baseline
                .map(|base| format!(" | comparison baseline {}", base.id))
                .unwrap_or_default()
        ),
    );

    draw_grid(&mut ops);
    if let Some(base) = baseline {
        draw_session_curves(&mut ops, base, true);
    }
    draw_session_curves(&mut ops, session, false);
    draw_table(&mut ops, session, baseline);

    text(&mut ops, 42.0, 168.0, 8.5, "How to read this report");
    text(
        &mut ops,
        42.0,
        154.0,
        7.5,
        "Red circles = right ear; blue crosses = left ear; grey dashed = baseline. Lower dB-R means a quieter digital tone was heard.",
    );
    text(
        &mut ops,
        42.0,
        140.0,
        7.5,
        "dB-R is an app-defined relative digital scale (0 = -90 dBFS; 60 = -30 dBFS). It is not dB SPL or clinical dB HL.",
    );
    text(&mut ops, 42.0, 121.0, 8.5, "Important limitations");
    text(
        &mut ops,
        42.0,
        107.0,
        7.5,
        "AirPods, their fit and processing, system volume, and room noise affect results. The test is unmasked air-conduction screening and cannot diagnose a cause.",
    );
    text(
        &mut ops,
        42.0,
        93.0,
        7.5,
        "Repeat an unexpected result under the same conditions and arrange a professional hearing assessment if you remain concerned.",
    );
    text(
        &mut ops,
        42.0,
        72.0,
        8.0,
        "Urgent: sudden hearing loss, rapid worsening, or hearing loss with earache/discharge needs prompt medical assessment; do not wait on this test.",
    );
    text(
        &mut ops,
        42.0,
        48.0,
        7.0,
        "Protocol: pulsed pure tones, 5 dB up / 10 dB down, 250-8000 Hz, maximum -30 dBFS. Generated by Hearing Tracker.",
    );

    let page = PdfPage::new(Mm(PAGE_WIDTH_MM), Mm(PAGE_HEIGHT_MM), ops);
    let mut document = PdfDocument::new("Personal Hearing Trend Report");
    let mut warnings = Vec::new();
    document
        .with_pages(vec![page])
        .save(&PdfSaveOptions::default(), &mut warnings)
}

fn draw_grid(ops: &mut Vec<Op>) {
    let grey = rgb(0.78, 0.80, 0.83);
    ops.push(Op::SetOutlineColor { col: grey });
    ops.push(Op::SetOutlineThickness { pt: Pt(0.55) });
    for (index, frequency) in FREQUENCIES_HZ.into_iter().enumerate() {
        let x = frequency_x(index);
        line(ops, x, PLOT_BOTTOM, x, PLOT_TOP);
        text(
            ops,
            x - 9.0,
            PLOT_TOP + 9.0,
            7.0,
            &frequency_label(frequency),
        );
    }
    for level in (0..=60).step_by(10) {
        let y = level_y(level as f32);
        line(ops, PLOT_LEFT, y, PLOT_RIGHT, y);
        text(ops, PLOT_LEFT - 24.0, y - 2.5, 7.0, &level.to_string());
    }
    text(ops, PLOT_LEFT - 35.0, PLOT_TOP + 25.0, 7.5, "dB-R");
    text(
        ops,
        PLOT_LEFT + 185.0,
        PLOT_TOP + 25.0,
        7.5,
        "Frequency (Hz)",
    );
}

fn draw_session_curves(ops: &mut Vec<Op>, session: &TestSession, baseline: bool) {
    if baseline {
        ops.push(Op::SetLineDashPattern {
            dash: LineDashPattern::new(0.0, &[5.0, 4.0]),
        });
    } else {
        ops.push(Op::SetLineDashPattern {
            dash: LineDashPattern::default(),
        });
    }
    for ear in [Ear::Right, Ear::Left] {
        let colour = if baseline {
            rgb(0.50, 0.52, 0.55)
        } else if ear == Ear::Right {
            rgb(0.82, 0.12, 0.16)
        } else {
            rgb(0.08, 0.32, 0.78)
        };
        ops.push(Op::SetOutlineColor { col: colour });
        ops.push(Op::SetOutlineThickness {
            pt: Pt(if baseline { 1.0 } else { 1.7 }),
        });
        let points: Vec<_> = FREQUENCIES_HZ
            .into_iter()
            .enumerate()
            .filter_map(|(index, frequency)| {
                session
                    .threshold(ear, frequency)
                    .and_then(|threshold| threshold.relative_db())
                    .map(|level| (frequency_x(index), level_y(level)))
            })
            .collect();
        for pair in points.windows(2) {
            line(ops, pair[0].0, pair[0].1, pair[1].0, pair[1].1);
        }
        if !baseline {
            for (x, y) in points {
                draw_symbol(ops, ear, x, y);
            }
            for (index, frequency) in FREQUENCIES_HZ.into_iter().enumerate() {
                if session
                    .threshold(ear, frequency)
                    .is_some_and(|threshold| threshold.outcome == ThresholdOutcome::NoResponse)
                {
                    draw_no_response(ops, ear, frequency_x(index), PLOT_BOTTOM + 3.0);
                }
            }
        }
    }
    ops.push(Op::SetLineDashPattern {
        dash: LineDashPattern::default(),
    });
}

fn draw_table(ops: &mut Vec<Op>, session: &TestSession, baseline: Option<&TestSession>) {
    let x = 575.0;
    text(ops, x, 448.0, 9.0, "Thresholds");
    text(ops, x, 432.0, 7.0, "Hz     R     L    change*");
    let deltas = baseline.and_then(|base| compare_sessions(session, base));
    for (row, frequency) in FREQUENCIES_HZ.into_iter().enumerate() {
        let y = 415.0 - row as f32 * 22.0;
        let right = threshold_text(session, Ear::Right, frequency);
        let left = threshold_text(session, Ear::Left, frequency);
        let change = deltas
            .as_ref()
            .map(|values| {
                let values: Vec<_> = values
                    .iter()
                    .filter(|value| value.frequency_hz == frequency)
                    .filter_map(|value| value.change_db)
                    .collect();
                if values.is_empty() {
                    "--".to_owned()
                } else {
                    format!("{:+.0}", values.iter().sum::<f32>() / values.len() as f32)
                }
            })
            .unwrap_or_else(|| "--".to_owned());
        text(
            ops,
            x,
            y,
            7.2,
            &format!("{:<5} {:>4} {:>5} {:>8}", frequency, right, left, change),
        );
    }
    text(ops, x, 227.0, 6.5, "*mean dB-R change");
    text(ops, x, 216.0, 6.5, "+ means stronger tone needed");
}

fn threshold_text(session: &TestSession, ear: Ear, frequency: u32) -> String {
    match session.threshold(ear, frequency) {
        Some(threshold) if threshold.outcome == ThresholdOutcome::NoResponse => "NR".into(),
        Some(threshold) => threshold
            .relative_db()
            .map(|value| format!("{value:.0}"))
            .unwrap_or_else(|| "--".into()),
        None => "--".into(),
    }
}

fn draw_symbol(ops: &mut Vec<Op>, ear: Ear, x: f32, y: f32) {
    match ear {
        Ear::Right => {
            let points = (0..16)
                .map(|index| {
                    let angle = std::f32::consts::TAU * index as f32 / 16.0;
                    LinePoint {
                        p: Point {
                            x: Pt(x + angle.cos() * 4.2),
                            y: Pt(y + angle.sin() * 4.2),
                        },
                        bezier: false,
                    }
                })
                .collect();
            ops.push(Op::DrawPolygon {
                polygon: Polygon {
                    rings: vec![PolygonRing { points }],
                    mode: PaintMode::Stroke,
                    winding_order: WindingOrder::NonZero,
                },
            });
        }
        Ear::Left => {
            line(ops, x - 4.0, y - 4.0, x + 4.0, y + 4.0);
            line(ops, x - 4.0, y + 4.0, x + 4.0, y - 4.0);
        }
    }
}

fn draw_no_response(ops: &mut Vec<Op>, ear: Ear, x: f32, y: f32) {
    draw_symbol(ops, ear, x, y + 7.0);
    line(ops, x, y + 2.0, x, y - 4.0);
    line(ops, x, y - 4.0, x - 3.0, y - 1.0);
    line(ops, x, y - 4.0, x + 3.0, y - 1.0);
}

fn text(ops: &mut Vec<Op>, x: f32, y: f32, size: f32, value: &str) {
    ops.extend([
        Op::StartTextSection,
        Op::SetTextCursor {
            pos: Point { x: Pt(x), y: Pt(y) },
        },
        Op::SetFont {
            font: PdfFontHandle::Builtin(BuiltinFont::Helvetica),
            size: Pt(size),
        },
        Op::ShowText {
            items: vec![TextItem::Text(value.to_owned())],
        },
        Op::EndTextSection,
    ]);
}

fn line(ops: &mut Vec<Op>, x1: f32, y1: f32, x2: f32, y2: f32) {
    ops.push(Op::DrawLine {
        line: Line {
            points: vec![
                LinePoint {
                    p: Point {
                        x: Pt(x1),
                        y: Pt(y1),
                    },
                    bezier: false,
                },
                LinePoint {
                    p: Point {
                        x: Pt(x2),
                        y: Pt(y2),
                    },
                    bezier: false,
                },
            ],
            is_closed: false,
        },
    });
}

fn rgb(r: f32, g: f32, b: f32) -> Color {
    Color::Rgb(Rgb {
        r,
        g,
        b,
        icc_profile: None,
    })
}

fn frequency_x(index: usize) -> f32 {
    PLOT_LEFT + index as f32 * (PLOT_RIGHT - PLOT_LEFT) / 7.0
}

fn level_y(level: f32) -> f32 {
    PLOT_TOP - level.clamp(0.0, 60.0) / 60.0 * (PLOT_TOP - PLOT_BOTTOM)
}

fn frequency_label(frequency: u32) -> String {
    if frequency >= 1_000 {
        format!("{}k", frequency / 1_000)
    } else {
        frequency.to_string()
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::domain::{
        AudioSetup, CEILING_DBFS, PROTOCOL_VERSION, QualityAssessment, SessionStatus,
    };

    #[test]
    fn generated_report_is_a_pdf() {
        let setup = AudioSetup {
            device_id: "test".into(),
            device_name: "AirPods".into(),
            backend: "ALSA".into(),
            sample_rate: 48_000,
            channels: 2,
            sink_volume_percent: Some(50.0),
            listening_mode: "Noise cancellation".into(),
            ceiling_dbfs: CEILING_DBFS,
            protocol_version: PROTOCOL_VERSION,
        };
        let mut session = TestSession::new(setup);
        session.status = SessionStatus::Completed;
        session.completed_at = Some(session.started_at);
        session.quality = Some(QualityAssessment {
            high_confidence: true,
            catch_trials: 6,
            false_positive_catches: 0,
            max_retest_difference_db: 0.0,
            reasons: vec![],
        });
        let bytes = generate_pdf(&session, None, Some("Test Person"));
        assert!(bytes.starts_with(b"%PDF-"));
        assert!(bytes.len() > 1_000);
    }
}
